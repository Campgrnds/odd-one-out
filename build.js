#!/usr/bin/env node
/*
 * build.js: turns source/real + source/ai into site/img + site/manifest.js
 *
 *   node build.js
 *
 * - Every image gets a random hex filename so the name never reveals the answer.
 * - With sharp installed (npm install), every image is re-encoded to JPEG:
 *   width capped at 1600px, size squeezed under 500KB, and all metadata
 *   (camera EXIF, AI-generator tags, etc.) stripped so it can't give the answer away.
 * - manifest.js stores each answer lightly encoded (base64), not as plain text.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = __dirname;
const SOURCES = [
  { dir: path.join(ROOT, 'source', 'real'), answer: 'REAL' },
  { dir: path.join(ROOT, 'source', 'ai'), answer: 'AI' },
];
const SITE_DIR = path.join(ROOT, 'site');
const IMG_DIR = path.join(SITE_DIR, 'img');
const MANIFEST_FILE = path.join(SITE_DIR, 'manifest.js');

const MAX_WIDTH = 1600;
const MAX_BYTES = 500 * 1024;
const EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

let sharp = null;
try {
  sharp = require('sharp');
} catch (err) {
  console.warn('! sharp is not installed, so images are copied without resizing or metadata stripping.');
  console.warn('  Run "npm install" in this folder to enable it (strongly recommended: a .png vs .jpg');
  console.warn('  extension or leftover camera data could hint at the answer).');
}

function listImages(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => !name.startsWith('.') && EXTENSIONS.has(path.extname(name).toLowerCase()))
    .sort()
    .map((name) => path.join(dir, name));
}

function newId(taken) {
  let id;
  do {
    id = crypto.randomBytes(4).toString('hex');
  } while (taken.has(id));
  taken.add(id);
  return id;
}

// Answer is encoded together with the image id so every entry looks different
// and REAL / AI entries are the same length.
function encodeAnswer(id, answer) {
  return Buffer.from(id + ':' + answer.charAt(0)).toString('base64');
}

async function optimize(file) {
  const meta = await sharp(file).metadata();
  let width = Math.min(meta.width || MAX_WIDTH, MAX_WIDTH);
  let quality = 85;
  let out;
  for (;;) {
    out = await sharp(file)
      .rotate() // apply EXIF orientation before metadata is dropped
      .resize({ width, withoutEnlargement: true })
      .flatten({ background: '#0A1628' }) // transparent PNGs get the card colour
      .jpeg({ quality, mozjpeg: true })
      .toBuffer();
    if (out.length <= MAX_BYTES) break;
    if (quality > 55) quality -= 10;
    else if (width > 600) width = Math.round(width * 0.85);
    else break;
  }
  return out;
}

async function main() {
  fs.rmSync(IMG_DIR, { recursive: true, force: true });
  fs.mkdirSync(IMG_DIR, { recursive: true });

  const taken = new Set();
  const entries = [];

  for (const source of SOURCES) {
    const files = listImages(source.dir);
    if (!files.length) console.warn(`! No images found in ${path.relative(ROOT, source.dir)}/`);

    for (const file of files) {
      const id = newId(taken);
      let outName;
      if (sharp) {
        outName = id + '.jpg';
        fs.writeFileSync(path.join(IMG_DIR, outName), await optimize(file));
      } else {
        outName = id + path.extname(file).toLowerCase().replace('.jpeg', '.jpg');
        fs.copyFileSync(file, path.join(IMG_DIR, outName));
      }
      const kb = Math.round(fs.statSync(path.join(IMG_DIR, outName)).size / 1024);
      console.log(`  ${source.answer.padEnd(4)}  ${path.basename(file)}  ->  img/${outName}  (${kb} KB)`);
      entries.push({ src: 'img/' + outName, answer: encodeAnswer(id, source.answer) });
    }
  }

  // Shuffle so the manifest order doesn't group real and AI images together.
  for (let i = entries.length - 1; i > 0; i--) {
    const j = crypto.randomInt(i + 1);
    [entries[i], entries[j]] = [entries[j], entries[i]];
  }

  const js =
    '// Generated by build.js. Do not edit by hand; rerun "node build.js" instead.\n' +
    'window.MANIFEST = ' +
    JSON.stringify(entries, null, 2) +
    ';\n';
  fs.writeFileSync(MANIFEST_FILE, js);

  const real = SOURCES[0].dir, ai = SOURCES[1].dir;
  console.log(
    `\nBuilt ${entries.length} images (${listImages(real).length} real, ${listImages(ai).length} AI) -> site/manifest.js`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
